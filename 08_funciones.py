def suma(n1,n2): # definimos una funcion y le pasamos los parametros
    return n1+n2 # return me devuelve el valor de la suma de los dos numeros
n1=int(input("ingrese el primer numero: ")) #numero 1 parametro 1
n2=int(input("ingrese el segundo numero: ")) # numero 2 parametro 2

print(f"el resultado de {n1}+{n2}={suma(n1,n2)}") # print al resultado llamando a la funcion

